"""Upstream HTTP relay: byte-faithful forwarding with disconnect propagation."""

from __future__ import annotations

import asyncio
import logging

import aiohttp
from aiohttp import web

from laplace_serve.inflight import RECORD, InflightRecord

log = logging.getLogger(__name__)

# Hop-by-hop headers are connection-scoped and must not be relayed end to end
# (RFC 7230 6.1). Stripped in both directions.
_HOP_BY_HOP = frozenset(
    {
        "connection",
        "keep-alive",
        "proxy-authenticate",
        "proxy-authorization",
        "te",
        "trailer",
        "transfer-encoding",
        "upgrade",
    }
)

# Request headers regenerated by the client for the upstream hop.
_DROP_REQUEST = _HOP_BY_HOP | {"host", "content-length"}
_DROP_CALLER_CREDENTIALS = {"authorization", "x-laplace-caller-authorization"}

# How often a request waiting for upstream response headers checks whether its
# downstream client is still connected. Module-level so tests can shrink it.
DISCONNECT_POLL_S = 1.0


class UpstreamProxy:
    """Relays requests to the LM Studio upstream, unbuffered and byte-faithful."""

    def __init__(
        self,
        session: aiohttp.ClientSession,
        upstream: str,
        auth_command: tuple[str, ...] = (),
    ):
        self._session = session
        self._upstream = upstream.rstrip("/")
        self._auth_command = auth_command
        self._credential: str | None = None

    async def start(self) -> None:
        if self._auth_command and not await self._refresh_credential():
            raise RuntimeError("upstream credential unavailable")

    async def _run_auth_command(self) -> str | None:
        proc = None
        try:
            proc = await asyncio.create_subprocess_exec(
                *self._auth_command,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.DEVNULL,
            )
            stdout, _ = await asyncio.wait_for(proc.communicate(), timeout=10.0)
        except asyncio.TimeoutError:
            if proc is not None:
                proc.kill()
                await proc.wait()
            return None
        except Exception:  # noqa: BLE001 - details could expose helper argv
            return None
        if proc.returncode != 0:
            return None
        try:
            value = stdout.decode().strip()
        except UnicodeDecodeError:
            return None
        return value or None

    async def _refresh_credential(self) -> bool:
        value = await self._run_auth_command()
        if value is None or not _is_header_safe_token(value):
            self._credential = None
            return False
        self._credential = value
        return True

    async def forward(
        self,
        request: web.Request,
        upstream_path: str,
        body: bytes,
    ) -> web.StreamResponse:
        url = self._upstream + upstream_path
        headers = filter_request_headers(
            request.headers, strip_credentials=self._credential is not None
        )
        if self._credential is not None:
            headers["Authorization"] = f"Bearer {self._credential}"

        try:
            upstream_resp = await _unless_disconnected(
                request,
                self._session.request(
                    request.method,
                    url,
                    headers=headers,
                    params=request.query.copy() if request.query_string else None,
                    data=body or None,
                ),
            )
        except (aiohttp.ClientConnectorError, aiohttp.ServerConnectionError, asyncio.TimeoutError) as exc:
            log.warning("proxy: upstream connect failed for %s: %s", upstream_path, exc)
            return web.json_response({"error": "upstream unavailable"}, status=502)

        if upstream_resp.status == 401 and self._auth_command:
            upstream_resp.release()
            if not await self._refresh_credential():
                return web.json_response({"error": "upstream_auth_unavailable"}, status=502)
            headers["Authorization"] = f"Bearer {self._credential}"
            try:
                upstream_resp = await _unless_disconnected(
                    request,
                    self._session.request(
                        request.method,
                        url,
                        headers=headers,
                        params=request.query.copy() if request.query_string else None,
                        data=body or None,
                    ),
                )
            except (
                aiohttp.ClientConnectorError,
                aiohttp.ServerConnectionError,
                asyncio.TimeoutError,
            ):
                return web.json_response({"error": "upstream unavailable"}, status=502)

        return await _relay(request, upstream_resp)

    async def probe_models(self, timeout: float = 5.0) -> bool:
        """Return True when the upstream answers /v1/models with any HTTP status.

        Any HTTP response (including 401/404) proves the upstream is reachable
        and alive. LM Studio returns 401 to unauthenticated /v1/models probes,
        and the daemon holds no secrets (D3), so demanding 200 would keep readyz
        permanently not-ready. Only a connect error or timeout means not ready.
        """
        headers = {}
        if self._credential is not None:
            headers["Authorization"] = f"Bearer {self._credential}"
        try:
            async with self._session.get(
                self._upstream + "/v1/models",
                headers=headers,
                timeout=aiohttp.ClientTimeout(total=timeout),
            ):
                return True
        except Exception as exc:  # noqa: BLE001
            log.warning("proxy: /v1/models probe failed: %s", exc)
            return False

    async def probe_api(self, timeout: float = 5.0) -> bool:
        """Require authenticated /v1/models success and the OpenAI list shape."""
        if self._credential is None:
            return False
        for attempt in range(2):
            try:
                async with self._session.get(
                    self._upstream + "/v1/models",
                    headers={"Authorization": f"Bearer {self._credential}"},
                    timeout=aiohttp.ClientTimeout(total=timeout),
                ) as response:
                    if response.status == 401 and attempt == 0:
                        if not await self._refresh_credential():
                            return False
                        continue
                    if response.status != 200:
                        return False
                    try:
                        payload = await response.json(content_type=None)
                    except (ValueError, aiohttp.ClientError):
                        return False
                    return isinstance(payload, dict) and isinstance(
                        payload.get("data"), list
                    )
            except (aiohttp.ClientError, asyncio.TimeoutError):
                return False
        return False


async def _unless_disconnected(request: web.Request, upstream_call):
    """Await the upstream request, aborting it if the downstream client leaves.

    aiohttp >= 3.9 does not cancel a handler when its client disconnects
    (handler_cancellation defaults to False, and web.run_app keeps it). A
    non-streaming upstream sends no bytes until generation ends, so no
    downstream write can fail either: without this watch the upstream keeps
    generating, and the admission slot stays held, until the model finishes.
    The call runs inline (no extra task) so relay timing is unchanged; a
    watcher cancels this handler task, which closes the upstream connection.
    """
    handler = asyncio.current_task()
    fired = False

    async def watch() -> None:
        nonlocal fired
        while True:
            await asyncio.sleep(DISCONNECT_POLL_S)
            transport = request.transport
            if transport is None or transport.is_closing():
                fired = True
                handler.cancel()
                return

    watcher = asyncio.ensure_future(watch())
    try:
        return await upstream_call
    except asyncio.CancelledError:
        if not fired:
            raise
        if hasattr(handler, "uncancel"):  # Python >= 3.11
            handler.uncancel()
        log.info(
            "proxy: client disconnected before upstream responded; aborted upstream %s",
            request.path,
        )
        # aiohttp treats a ConnectionError from a handler as a premature
        # client disconnection and drops the connection quietly.
        raise ConnectionResetError("downstream client disconnected") from None
    finally:
        watcher.cancel()


async def _relay(
    request: web.Request,
    upstream_resp: aiohttp.ClientResponse,
) -> web.StreamResponse:
    return await relay_after_commit(request, upstream_resp, b"")


async def relay_after_commit(
    request: web.Request,
    upstream_resp: aiohttp.ClientResponse,
    first_chunk: bytes,
) -> web.StreamResponse:
    response = web.StreamResponse(
        status=upstream_resp.status,
        headers=_filter_response_headers(upstream_resp.headers),
    )
    # Status and headers are flushed here, before the first body chunk, and are
    # never buffered (streamed-header edge c). A non-200 upstream is relayed the
    # same way, status and body as-is (edge a).
    await response.prepare(request)
    # Opt-in progress record (laplace_serve.inflight). Each chunk is observed
    # only after it has been written, so the client stream is unchanged.
    record = request.get(RECORD)

    try:
        if first_chunk:
            await response.write(first_chunk)
            if record is not None:
                record = _observe(record, first_chunk)
        async for chunk in upstream_resp.content.iter_any():
            await response.write(chunk)
            if record is not None:
                record = _observe(record, chunk)
    except (ConnectionResetError, asyncio.CancelledError):
        # Downstream client disconnected mid-stream. Abort the upstream request
        # rather than draining it (R7), then re-raise to unwind the handler.
        upstream_resp.close()
        raise
    except (aiohttp.ClientError, asyncio.TimeoutError) as exc:
        # Upstream died mid-stream, or a read/socket timeout fired. Close
        # downstream with no synthesized [DONE] (edge b); the truncated stream is
        # the honest signal. The session builds with total=None so a timeout here
        # should not happen, but handling it keeps any future timeout graceful
        # rather than an unhandled TimeoutError unwinding the handler.
        log.warning("proxy: upstream stream error: %s", exc)
        upstream_resp.close()
        return response
    finally:
        upstream_resp.release()

    await response.write_eof()
    return response


def _observe(record: InflightRecord, chunk: bytes) -> InflightRecord | None:
    """Feed a progress record; a failure there must never touch the stream.

    On any Exception the record is marked failed and observation stops for this
    request. BaseException (cancellation) still propagates. The log line names
    only the exception type, never stream content.
    """
    try:
        record.observe(chunk)
    except Exception as exc:  # noqa: BLE001 - observation is best-effort
        record.observer_failed = True
        log.warning("inflight: progress observer failed (%s); stopped for this request",
                    type(exc).__name__)
        return None
    return record


def filter_request_headers(headers, *, strip_credentials: bool = False) -> dict[str, str]:
    dropped = _DROP_REQUEST | (_DROP_CALLER_CREDENTIALS if strip_credentials else set())
    return {key: value for key, value in headers.items() if key.lower() not in dropped}


def _is_header_safe_token(value: str) -> bool:
    return bool(value) and all(0x21 <= ord(char) <= 0x7E for char in value)


def _filter_response_headers(headers) -> dict[str, str]:
    return {key: value for key, value in headers.items() if key.lower() not in _HOP_BY_HOP}
