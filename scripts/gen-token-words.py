#!/usr/bin/env python3
"""Regenerate (or check) laplace_serve/_token_words.py. Offline measurement tool.

Not a runtime dependency: laplaced stays stdlib-only. This needs
``transformers`` (no torch) and the local tokenizer files of the models the
word costs must hold for. It reads tokenizer files only; it never calls LM Studio.

Word source: the most frequent ASCII words in the running interpreter's
stdlib sources (tests and site-packages excluded). A word is kept at cost 1
when ``w``, `` w``, ``W`` and `` W`` (W = capitalised) each encode to exactly
one token on every tokenizer given, and at cost 2 (length >= 4, the
COST2_LIMIT most frequent) when the worst of those is two tokens.

Usage:
  gen-token-words.py MODEL_DIR...           print the new module to stdout
  gen-token-words.py --check MODEL_DIR...   verify the committed lists
"""

import collections
import glob
import os
import re
import sys
import sysconfig

POOL = 12000
COST2_LIMIT = 2000
WORD = re.compile(r"(?<![A-Za-z0-9_])[A-Za-z]+(?![A-Za-z0-9])")
SHAPE = re.compile(r"[A-Z]?[a-z]+")


def worst_tokens(tokenizers, word):
    variants = (word, " " + word, word.capitalize(), " " + word.capitalize())
    return max(
        len(tok.encode(v, add_special_tokens=False)) for tok in tokenizers for v in variants
    )


def main(argv):
    check = "--check" in argv
    dirs = [a for a in argv if a != "--check"]
    if not dirs:
        sys.exit(__doc__)
    from transformers import AutoTokenizer

    tokenizers = [AutoTokenizer.from_pretrained(d, local_files_only=True) for d in dirs]
    if check:
        sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
        from laplace_serve._token_words import COST1, COST2

        bad = [(w, 1) for w in COST1 if worst_tokens(tokenizers, w) > 1]
        bad += [(w, 2) for w in COST2 if worst_tokens(tokenizers, w) > 2]
        print(f"checked {len(COST1)} cost-1 and {len(COST2)} cost-2 words "
              f"on {len(tokenizers)} tokenizers: {len(bad)} over cost")
        for word, cost in bad:
            print(f"  OVER {word!r} listed at {cost}")
        sys.exit(1 if bad else 0)

    stdlib = sysconfig.get_paths()["stdlib"]
    files = [f for f in glob.glob(os.path.join(stdlib, "**", "*.py"), recursive=True)
             if "/test" not in f and "site-packages" not in f]
    counts = collections.Counter()
    for path in sorted(files):
        with open(path, errors="ignore") as handle:
            counts.update(w.lower() for w in WORD.findall(handle.read()) if SHAPE.fullmatch(w))
    cost1, cost2 = [], []
    for word, _ in counts.most_common(POOL):
        worst = worst_tokens(tokenizers, word)
        if worst == 1:
            cost1.append(word)
        elif worst == 2 and len(word) >= 4 and len(cost2) < COST2_LIMIT:
            cost2.append(word)

    def block(words):
        lines, line = [], ""
        for w in sorted(words):
            if len(line) + len(w) + 1 > 76:
                lines.append(line)
                line = ""
            line = f"{line} {w}" if line else w
        lines.append(line)
        return "\n".join(lines)

    names = ", ".join(os.path.basename(d.rstrip("/")) for d in dirs)
    print(f'''"""Generated by scripts/gen-token-words.py; do not edit by hand.

Lowercase ASCII words whose worst token count, written as w, " w", W and " W",
is 1 (COST1) or 2 (COST2) on each of these tokenizers: {names}.
Source: the {POOL} most frequent words in the CPython {sys.version_info[0]}.{sys.version_info[1]} stdlib sources.
"""

COST1 = frozenset("""
{block(cost1)}
""".split())

COST2 = frozenset("""
{block(cost2)}
""".split())''')


if __name__ == "__main__":
    main(sys.argv[1:])
